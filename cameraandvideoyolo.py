checkbox_frame.pack(pady=10)

style_checkbox = {"bg": BG_MAIN, "fg": FG_TEXT, "selectcolor": BG_FRAME, "font": ("Arial", 12)}
var8 = tk.IntVar(value=1)
var11 = tk.IntVar(value=1)
var12 = tk.IntVar(value=1)

tk.Checkbutton(checkbox_frame, text="Enable Model-8", variable=var8, **style_checkbox).grid(row=0, column=0, padx=10)
tk.Checkbutton(checkbox_frame, text="Enable Model-11", variable=var11, **style_checkbox).grid(row=0, column=1, padx=10)
tk.Checkbutton(checkbox_frame, text="Enable Model-12", variable=var12, **style_checkbox).grid(row=0, column=2, padx=10)

# ==========================================
# CAMERA / VIDEO SETTINGS
# ==========================================
CAM_WIDTH, CAM_HEIGHT = 900, 550

# ==========================================
# DRAW HORIZONTAL BAR
# ==========================================
def draw_horizontal_bar(frame, start_x, start_y, width, height, value, max_value, color, label=""):
    cv2.rectangle(frame, (start_x, start_y), (start_x + width, start_y + height), (50,50,50), -1)
    fill_width = int((value / max_value) * width)
    cv2.rectangle(frame, (start_x, start_y), (start_x + fill_width, start_y + height), color, -1)
    cv2.putText(frame, f"{label} {value:.1f}%", (start_x + 5, start_y + height - 3),
                cv2.FONT_HERSHEY_SIMPLEX, 0.5, (255,255,255), 1)

# ==========================================
# UPDATE FRAME (CAMERA OR VIDEO)
# ==========================================
def update_frame():
    global camera_running, video_running, cap, prev_time, fps, model_confidences
    if not camera_running and not video_running:
        return

    ret, frame = cap.read()
    if not ret:
        stop_all()
        return

    # Resize frame
    frame = cv2.resize(frame, (CAM_WIDTH, CAM_HEIGHT))

    # FPS calculation
    curr_time = time.time()
    fps = 1 / (curr_time - prev_time)
    prev_time = curr_time
    cv2.putText(frame, f"FPS: {fps:.1f}", (10, 30), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (0,255,0), 2)

    # Reset class counts for frame
    class_counts_frame = {}

    # Process models
    enabled_models = {"Model-8": var8.get(), "Model-11": var11.get(), "Model-12": var12.get()}
    y_offset = 50
    bar_width = 180
    bar_height = 20
    gap = 10

    for model_name, enabled in enabled_models.items():
        if enabled == 1:
            results = models[model_name](frame, stream=True)
            avg_conf = 0
            count = 0
            for r in results:
                for box in r.boxes:
                    x1,y1,x2,y2 = box.xyxy[0].cpu().numpy().astype(int)
                    conf = float(box.conf[0])
                    cls = models[model_name].names[int(box.cls[0])]
                    color = model_colors[model_name]
                    cv2.rectangle(frame, (x1,y1), (x2,y2), color, 2)
                    cv2.putText(frame, f"{model_name[-2:]}:{cls} {conf:.2f}", (x1, y1-10),
                                cv2.FONT_HERSHEY_SIMPLEX, 0.55, color, 2)
                    avg_conf += conf
                    count += 1
                    class_counts_frame[cls] = class_counts_frame.get(cls, 0) + 1

            # Update model confidence history
            confidence_percent = (avg_conf / count)*100 if count > 0 else 0
            model_confidences[model_name].append(confidence_percent)
            if len(model_confidences[model_name]) > MAX_HISTORY:
                model_confidences[model_name].pop(0)

            # Draw model confidence bars
            start_x = CAM_WIDTH - 200
            draw_horizontal_bar(frame, start_x, y_offset, bar_width, bar_height,
                                np.mean(model_confidences[model_name]), 100,
                                model_colors[model_name], label=model_name)
            y_offset += bar_height + gap

    # Draw class distribution bars under model bars
    class_y_offset = y_offset + 20
    for cls, val in class_counts_frame.items():
        color = (200,150,50)
        draw_horizontal_bar(frame, CAM_WIDTH - 200, class_y_offset, bar_width, bar_height,
                            min(val, MAX_HISTORY*2), MAX_HISTORY*2, color, label=cls)
        class_y_offset += bar_height + gap

    # Display frame
    rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
    img = ImageTk.PhotoImage(Image.fromarray(rgb))
    video_label.imgtk = img
    video_label.config(image=img)

    video_label.after(10, update_frame)

# ==========================================
# BUTTONS
