def start_camera():
    global camera_running, video_running, cap
    stop_all()
    camera_running = True
    cap = cv2.VideoCapture(0)
    if not cap.isOpened():
        messagebox.showerror("Error", "Unable to open camera")
        return
    update_frame()

def upload_video():
    global video_running, camera_running, cap
    stop_all()
    file_path = filedialog.askopenfilename(title="Select Video", filetypes=[("Video files","*.mp4 *.avi")])
    if not file_path:
        return
    cap = cv2.VideoCapture(file_path)
    if not cap.isOpened():
        messagebox.showerror("Error", "Cannot open video file")
        return
    video_running = True
    update_frame()

def stop_all():
    global camera_running, video_running, cap
    camera_running = False
    video_running = False
    if cap:
        cap.release()
    video_label.config(image="")

