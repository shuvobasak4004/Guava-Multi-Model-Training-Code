import tkinter as tk
from tkinter import messagebox, filedialog
from ultralytics import YOLO
import cv2
from PIL import Image, ImageTk
import numpy as np
import time

# ---------------------------------------
# LOAD MODELS
# ---------------------------------------
models = {
    "Model-8": YOLO(r"D:\JU\yoloresult\result_model\best_yolo8.pt"),
    "Model-11": YOLO(r"D:\JU\yoloresult\result_model\best_yolo11.pt"),
    "Model-12": YOLO(r"D:\JU\yoloresult\result_model\best_yolo12.pt")
}

model_colors = {
    "Model-8": (179, 230, 255),
    "Model-11": (0, 128, 255),
    "Model-12": (255, 128, 0)
}

# ---------------------------------------
# THEME COLORS
# ---------------------------------------
BG_MAIN = "#0d1b2a"
BG_FRAME = "#1b263b"
FG_TEXT = "#e0e6ed"

# ---------------------------------------
# GUI SETUP
# ---------------------------------------
root = tk.Tk()
root.title("YOLO Multi-Model Camera & Video Dashboard")
root.geometry("1300x800")
root.configure(bg=BG_MAIN)

camera_running = False
video_running = False
cap = None

# ---------------------------------------
# Store model confidence and class distribution
# ---------------------------------------
model_confidences = {"Model-8": [], "Model-11": [], "Model-12": []}
MAX_HISTORY = 50

# FPS
prev_time = time.time()
fps = 0

# ==========================================
# MAIN FRAME
# ==========================================
main_frame = tk.Frame(root, bg=BG_MAIN)
main_frame.pack(pady=10)

video_label = tk.Label(main_frame, bg=BG_FRAME, bd=3, relief="solid")
video_label.pack()

# ==========================================
